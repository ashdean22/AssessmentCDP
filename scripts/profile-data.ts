// ---------------------------------------------------------------- subscribers
const subs = load("subscribers.csv");
section("subscribers.csv");
console.log(`Columns: ${Object.keys(subs[0]).map((c) => `\`${c}\``).join(", ")}\n`);
const subEmails = subs.map((r) => r.email ?? "");
const normSub = subEmails.map((e) => e.trim().toLowerCase());
kv({
  rows: subs.length,
  "distinct raw emails": new Set(subEmails).size,
  "distinct normalized emails": new Set(normSub).size,
  "duplicate rows after normalize": subs.length - new Set(normSub).size,
});
console.log("### Email issues\n");
kv(emailIssues(subEmails));
console.log("### status values (raw)\n");
table(counts(subs.map((r) => r.status ?? "")));
console.log("### acquisition_source values (raw)\n");
table(counts(subs.map((r) => r.acquisition_source ?? "")));
console.log("### signup_date formats\n");
table(counts(subs.map((r) => dateShape(r.signup_date ?? ""))));
console.log("### last_open_date formats\n");
table(counts(subs.map((r) => dateShape(r.last_open_date ?? ""))));
console.log("### Sample unusual dates\n");
const odd = subs
  .flatMap((r) => [r.signup_date, r.last_open_date])
  .filter((d) => d && !/^\d{4}-\d{2}-\d{2}$/.test(d.trim()));
table(counts(odd), 15);

