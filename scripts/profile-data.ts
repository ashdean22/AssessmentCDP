/**
 * Profiles the three source CSVs so cleaning rules are based on what's
 * actually in the data, not guesses. Prints a markdown report to stdout:
 *
 *   npm run profile > DATA_NOTES.md
 */
import { readFileSync } from "node:fs";
import { parse } from "csv-parse/sync";

type Row = Record<string, string>;

function load(file: string): Row[] {
  return parse(readFileSync(`data/${file}`, "utf8"), {
    columns: true,
    skip_empty_lines: true,
    relax_column_count: true,
    bom: true,
  });
}

function counts(values: string[]): Map<string, number> {
  const m = new Map<string, number>();
  for (const v of values) m.set(v, (m.get(v) ?? 0) + 1);
  return new Map([...m].sort((a, b) => b[1] - a[1]));
}

function table(m: Map<string, number>, limit = 40) {
  const rows = [...m].slice(0, limit);
  console.log("| value | count |\n| --- | --- |");
  for (const [k, n] of rows) console.log(`| \`${k === "" ? "(empty)" : k}\` | ${n} |`);
  if (m.size > limit) console.log(`| … ${m.size - limit} more | |`);
  console.log();
}

/** Classify a date string by shape so every format present is visible. */
function dateShape(s: string): string {
  if (s.trim() === "") return "(empty)";
  return s
    .trim()
    .replace(/[0-9]/g, "9")
    .replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*\b/i, "Mon");
}

function emailIssues(emails: string[]) {
  const issues = {
    empty: 0,
    leadingOrTrailingSpace: 0,
    uppercase: 0,
    noAt: 0,
    plusAlias: 0,
    multipleAt: 0,
    invalidChars: 0,
  };
  for (const e of emails) {
    if (e === "") { issues.empty++; continue; }
    if (e !== e.trim()) issues.leadingOrTrailingSpace++;
    if (e !== e.toLowerCase()) issues.uppercase++;
    const at = (e.match(/@/g) ?? []).length;
    if (at === 0) issues.noAt++;
    if (at > 1) issues.multipleAt++;
    if (/\+/.test(e.split("@")[0] ?? "")) issues.plusAlias++;
    if (!/^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$/.test(e.trim())) issues.invalidChars++;
  }
  return issues;
}

function section(title: string) {
  console.log(`\n## ${title}\n`);
}

function kv(obj: Record<string, number | string>) {
  console.log("| metric | value |\n| --- | --- |");
  for (const [k, v] of Object.entries(obj)) console.log(`| ${k} | ${v} |`);
  console.log();
}

