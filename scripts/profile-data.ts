// Visitor ↔ email stitching stats
const visitorEmails = new Map<string, Set<string>>();
web.forEach((r) => {
  const e = (r.email ?? "").trim().toLowerCase();
  if (!e) return;
  visitorEmails.set(r.visitor_id, new Set([...(visitorEmails.get(r.visitor_id) ?? []), e]));
});
const emailVisitors = new Map<string, Set<string>>();
visitorEmails.forEach((es, v) => es.forEach((e) => emailVisitors.set(e, new Set([...(emailVisitors.get(e) ?? []), v]))));
console.log("### Identity stitching\n");
kv({
  "visitors with ≥1 email": visitorEmails.size,
  "visitors with >1 distinct email (shared device?)": [...visitorEmails.values()].filter((s) => s.size > 1).length,
  "emails seen on >1 visitor": [...emailVisitors.values()].filter((s) => s.size > 1).length,
  "events on visitors that have an email (inherit link)": web.filter((r) => visitorEmails.has(r.visitor_id)).length,
});

