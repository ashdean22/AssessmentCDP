// ---------------------------------------------------------------- web events
const web = load("web_events.csv");
section("web_events.csv");
console.log(`Columns: ${Object.keys(web[0]).map((c) => `\`${c}\``).join(", ")}\n`);
const webEmails = web.map((r) => r.email ?? "");
const webWithEmail = webEmails.filter((e) => e.trim() !== "");
const normWeb = new Set(webWithEmail.map((e) => e.trim().toLowerCase()));
const subSet = new Set(normSub);
kv({
  rows: web.length,
  "distinct visitor_id": new Set(web.map((r) => r.visitor_id)).size,
  "rows with email": webWithEmail.length,
  "distinct emails": normWeb.size,
  "emails matching a subscriber": [...normWeb].filter((e) => subSet.has(e)).length,
  "emails NOT matching any subscriber": [...normWeb].filter((e) => !subSet.has(e)).length,
  "distinct pages": new Set(web.map((r) => r.page)).size,
});
